// Accessing Array Elements using Index

let cities = ["Bhavnagar", "Ahmedabad", "Surat", "Rajkot", "Vadodara"];

console.log("array :", cities);
console.log("first city :", cities[0]);
console.log("favorite city :", cities[3]);
console.log("last city :", cities[cities.length - 1]);

// Modifying Array Elements

cities[3] = "Mumbai";
console.log("favorite city :", cities[3]);
console.log("Modify array :", cities);

